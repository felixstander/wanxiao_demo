def explain_plan(plan_type: str) -> dict:
    if plan_type not in PLAN_DETAILS:
        return {"error": f"未知方案类型: {plan_type}，可选: {list(PLAN_DETAILS.keys())}"}
    return {
        "plan_type": plan_type,
        "coverages": PLAN_DETAILS[plan_type]
    }


def main():
    parser = argparse.ArgumentParser(description="车险方案讲解工具")
    parser.add_argument("--plan_type", default="全面方案", help="方案类型")
    args = parser.parse_args()
    result = explain_plan(args.plan_type)
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
